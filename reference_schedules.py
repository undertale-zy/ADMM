def inverse_softplus(values: Tensor) -> Tensor:
    """Stable inverse of softplus for strictly positive tensors."""

    if torch.any(values <= 0):
        raise ValueError("schedule values must be positive")
    return values + torch.log(-torch.expm1(-values))


def schedule_tensors(
    schedule: str | Sequence[Sequence[float]],
    *,
    dtype: torch.dtype = torch.float32,
) -> tuple[Tensor, Tensor, Tensor]:
    """Return positive ``c``, ``tau`` and ``beta`` tensors."""

    rows = REFERENCE_SCHEDULES[schedule] if isinstance(schedule, str) else schedule
    values = torch.tensor(rows, dtype=dtype)
    if values.ndim != 2 or values.shape[1] != 3:
        raise ValueError("a schedule must have shape [layers, 3]")
    return values[:, 0], values[:, 1], values[:, 2]


def load_schedule_into_model(
    model: nn.Module,
    schedule: str | Sequence[Sequence[float]],
) -> None:
    """Load documented positive values into a model's raw scalar parameters."""

    c, tau, beta = schedule_tensors(schedule)
    raw_parameters = (model.raw_c, model.raw_tau, model.raw_beta)  # type: ignore[attr-defined]
    if any(parameter.shape != c.shape for parameter in raw_parameters):
        raise ValueError("schedule layer count does not match model")
    with torch.no_grad():
        for parameter, positive in zip(raw_parameters, (c, tau, beta)):
            parameter.copy_(inverse_softplus(positive).to(parameter))


def stage1_teacher_raw() -> tuple[Tensor, Tensor, Tensor]:
    """Return raw Stage-1 tensors suitable for frozen guide buffers."""

    return tuple(inverse_softplus(value) for value in schedule_tensors("stage1_scalar_8"))  # type: ignore[return-value]


